/**
 * Точечное затемнение блика под одной строкой текста.
 *
 * Кладётся внутрь блока со своей строкой и повторяет её размер:
 * у заголовка одно пятно, у слогана — своё. Одно общее пятно на оба
 * элемента читалось как огромная клякса.
 *
 * Размер задаётся снаружи, потому что строки разной высоты.
 */
export default function GlareShield({ className = '' }) {
    return (
        <div
            aria-hidden
            className={`pointer-events-none absolute left-1/2 top-1/2 -z-10 -translate-x-1/2 -translate-y-1/2 ${className}`}
            style={{
                background:
                    // Длинный хвост: край пятна не должен читаться.
                    'radial-gradient(ellipse 50% 50% at 50% 50%,'
                    + ' rgba(3,5,10,0.94) 0%,'
                    + ' rgba(3,5,10,0.85) 30%,'
                    + ' rgba(3,5,10,0.6) 48%,'
                    + ' rgba(3,5,10,0.32) 64%,'
                    + ' rgba(3,5,10,0.12) 80%,'
                    + ' transparent 100%)',
            }}
        />
    );
}
