/**
 * Точечное затемнение блика под одной строкой текста.
 *
 * Кладётся внутрь блока со своей строкой: у заголовка одно пятно,
 * у слогана — своё. Одно общее на оба элемента читалось как клякса.
 *
 * Поверх градиента идёт размытие: без него край пятна виден как
 * чёткая дуга, сколько шагов в переход ни добавляй.
 *
 * Размер задаётся снаружи, потому что строки разной высоты.
 */
export default function GlareShield({ className = '' }) {
    return (
        <div
            aria-hidden
            className={`pointer-events-none absolute left-1/2 top-1/2 -z-10 -translate-x-1/2 -translate-y-1/2 blur-3xl ${className}`}
            style={{
                background:
                    'radial-gradient(ellipse 50% 50% at 50% 50%,'
                    + ' rgba(3,5,10,0.95) 0%,'
                    + ' rgba(3,5,10,0.9) 38%,'
                    + ' rgba(3,5,10,0.7) 56%,'
                    + ' rgba(3,5,10,0.4) 72%,'
                    + ' rgba(3,5,10,0.15) 86%,'
                    + ' transparent 100%)',
            }}
        />
    );
}
